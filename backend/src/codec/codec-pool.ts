/**
 * Codec worker-thread pool (LLD Part 2 §14.1). Each job goes to the thread with the fewest jobs
 * in flight. A thread error terminates that worker, rejects its jobs with `CONVERSION_FAILED`
 * and is replaced by a new thread.
 *
 * @module
 */
import { Worker } from 'node:worker_threads';
import type { DocKind, FileFormat, ConversionNotice, UnsupportedFinding } from '@open-docex/shared/protocol';
import type { ErrorCode } from '@open-docex/shared/errors';
import { OpenDocexError } from '@open-docex/shared/errors';
import { engineError } from '../errors/engine-error.js';
import type { Logger } from '../log/logger.js';

/** Limits handed to a codec thread. */
export interface CodecLimits {
  soffice: string;
  timeoutMs: number;
  maxFlatXmlBytes: number;
  maxFileBytes: number;
}

/** One unit of work (§14.1). All paths are generated by the service, never document input. */
export type CodecJob =
  | { op: 'import'; format: FileFormat; inPath: string; workDir: string; profileDir: string; assetDir: string; limits: CodecLimits }
  | { op: 'export'; kind: DocKind; format: FileFormat; modelJson: string; workDir: string; profileDir: string; assetDir: string; limits: CodecLimits }
  | { op: 'probe'; workDir: string; profileDir: string; limits: CodecLimits };

/** What an import job returns. */
export interface ImportJobResult {
  kind: DocKind;
  snapshot: unknown;
  findings: UnsupportedFinding[];
  assetIds: string[];
  conversions?: ConversionNotice[];
}

/** What an export job returns; the buffer is transferred, not copied. */
export interface ExportJobResult {
  bytes: ArrayBuffer;
}

/** Messages a codec thread posts to the pool. */
export type ThreadMessage =
  | { id: number; ok: true; result: unknown }
  | { id: number; ok: false; code: ErrorCode; message: string }
  | { log: 'debug' | 'info' | 'warn' | 'error'; message: string };

/** Thrown, as the `cause` of `CONVERSION_FAILED`, when a worker thread died. */
export class ThreadCrashError extends Error {
  constructor(message: string, options?: { cause?: unknown }) {
    super(message, options);
    this.name = 'ThreadCrashError';
  }
}

/** The pool surface the service uses; fakes implement it in tests. */
export interface CodecPoolLike {
  run<R>(job: CodecJob, transfer?: ArrayBuffer[]): Promise<R>;
  close(): Promise<void>;
}

interface Pending {
  resolve(v: unknown): void;
  reject(e: unknown): void;
}

interface Thread {
  worker: Worker;
  inflight: Map<number, Pending>;
}

/** Options of {@link CodecPool}. */
export interface CodecPoolOptions {
  size: number;
  /** The compiled entry that calls `startCodecThread` (§14.1). */
  entry: URL;
  logger: Logger;
}

/** The worker pool. */
export class CodecPool implements CodecPoolLike {
  readonly #o: CodecPoolOptions;
  readonly #threads: Thread[] = [];
  #nextId = 1;
  #closed = false;

  constructor(o: CodecPoolOptions) {
    if (!Number.isInteger(o.size) || o.size < 1) throw new RangeError('CodecPool size must be a positive integer');
    this.#o = o;
    for (let i = 0; i < o.size; i += 1) this.#threads.push(this.#spawn());
  }

  #spawn(): Thread {
    const worker = new Worker(this.#o.entry);
    worker.unref();
    const t: Thread = { worker, inflight: new Map() };
    worker.on('message', (m: ThreadMessage) => {
      if ('log' in m) {
        this.#o.logger[m.log](m.message);
        return;
      }
      const p = t.inflight.get(m.id);
      if (p === undefined) return;
      t.inflight.delete(m.id);
      if (m.ok) p.resolve(m.result);
      else p.reject(new OpenDocexError(m.code, m.message));
    });
    const died = (cause: unknown): void => {
      if (this.#closed) return;
      const i = this.#threads.indexOf(t);
      if (i < 0) return;
      this.#o.logger.error('codec thread failed; replacing it');
      this.#threads[i] = this.#spawn();
      void t.worker.terminate();
      for (const p of t.inflight.values()) {
        p.reject(
          engineError('CONVERSION_FAILED', {
            message: 'The codec thread failed',
            cause: new ThreadCrashError('codec thread failed', { cause }),
          }),
        );
      }
      t.inflight.clear();
    };
    worker.on('error', died);
    worker.on('exit', (code) => died(new Error(`exit code ${String(code)}`)));
    return t;
  }

  /** Runs `job` on the least busy thread. `transfer` lists buffers to move into the thread. */
  run<R>(job: CodecJob, transfer: ArrayBuffer[] = []): Promise<R> {
    if (this.#closed) return Promise.reject(engineError('CONVERSION_FAILED', { message: 'The codec pool is closed' }));
    let best = this.#threads[0] as Thread;
    for (const t of this.#threads) if (t.inflight.size < best.inflight.size) best = t;
    const id = this.#nextId++;
    return new Promise<R>((resolve, reject) => {
      best.inflight.set(id, { resolve: resolve, reject });
      best.worker.postMessage({ id, job }, transfer);
    });
  }

  /** Terminates every thread; jobs in flight reject. */
  async close(): Promise<void> {
    if (this.#closed) return;
    this.#closed = true;
    await Promise.all(
      this.#threads.map(async (t) => {
        for (const p of t.inflight.values()) {
          p.reject(engineError('CONVERSION_FAILED', { message: 'The codec pool was closed' }));
        }
        t.inflight.clear();
        await t.worker.terminate();
      }),
    );
  }
}
